"""Generate assets/web/icons.js: Phosphor icons (MIT) for the Web Companion.

Reads the glyph outlines from the Phosphor fonts the app already uses
(phosphor_flutter in the pub cache), so the web pages show the very same
icons as the app's AppIcons. Run after adding a name to ICONS:

    pip install fonttools
    python tool/web_icons.py
"""
