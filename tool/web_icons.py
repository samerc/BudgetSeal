ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = sorted(glob.glob(os.path.expanduser(
    '~/AppData/Local/Pub/Cache/hosted/pub.dev/phosphor_flutter-*')) + glob.glob(
    os.path.expanduser('~/.pub-cache/hosted/pub.dev/phosphor_flutter-*')))[-1]


def codepoints(weight):
    src = open(os.path.join(PKG, 'lib', 'src',
                            f'phosphor_icons_{weight.lower()}.dart'), encoding='utf-8').read()
    out = {}
    for line in src.splitlines():
        line = line.strip()
        if line.startswith('static const ') and 'IconData(0x' in line:
            name = line.split()[2]
            out[name] = int(line.split('IconData(')[1].split(',')[0], 16)
    return out


def main():
    fonts = {'Regular': 'Phosphor.ttf', 'Fill': 'Phosphor-Fill.ttf'}
    paths = {}
    for weight, file in fonts.items():
        font = TTFont(os.path.join(PKG, 'lib', 'fonts', file))
        glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
        ascent = font['hhea'].ascent
        cps = codepoints(weight)
        for web, (name, w) in ICONS.items():
            if w != weight:
                continue
            pen = SVGPathPen(glyphs, ntos=lambda v: ('%.1f' % v).rstrip('0').rstrip('.'))
            # Font units (y up, baseline at 0) -> SVG (y down, 1024 box).
            glyphs[cmap[cps[name]]].draw(TransformPen(pen, (1, 0, 0, -1, 0, ascent)))
            paths[web] = pen.getCommands()
    missing = set(ICONS) - set(paths)
    assert not missing, missing
    lines = [
        '// Generated by tool/web_icons.py — do not edit.',
        '// Phosphor Icons (MIT, https://phosphoricons.com), the same set as the app.',
        "'use strict';",
        'const PH = {',
    ]
    for k in ICONS:
        lines.append(f"  {k}: '{paths[k]}',")
    lines.append('};')
    open(os.path.join(ROOT, 'assets', 'web', 'icons.js'), 'w', encoding='utf-8',
         newline='\n').write('\n'.join(lines) + '\n')
    print(len(paths), 'icons')


main()
